// Copies the live deployment (addresses, deploy block, config) and the ABIs from ../contracts into
// src/generated/contracts.json, so the app never hard-codes an address. Run after every deploy:
//   pnpm sync-contracts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const C = resolve(import.meta.dirname, "../../contracts");
const read = (p) => JSON.parse(readFileSync(resolve(C, p), "utf8"));
const abi = (file, name) => read(`out/${file}/${name}.json`).abi;

// DEPLOYMENTS_DIR (relative to contracts/): "deployments" = the team's shared stack (committed),
// "deployments/local" = your own stack (gitignored) -> src/generated/contracts.local.json, used with VITE_DEPLOYMENT=local
const DIR = process.env.DEPLOYMENTS_DIR?.trim() || "deployments";
const dep = read(`${DIR}/countersign-9800.json`);
const bond = read(`${DIR}/bond-9800.json`);
if (dep.deployBlock === undefined) throw new Error(`${DIR}/countersign-9800.json has no deployBlock: redeploy with the current DeployCountersign.s.sol`);

const errorsOnly = (a) => a.filter((x) => x.type === "error");
const seen = new Set();
const errors = [
  ...errorsOnly(abi("CMTATStandalone.sol", "CMTATStandalone")),
  ...errorsOnly(abi("QoreChainHybridHolderRule.sol", "QoreChainHybridHolderRule")),
  ...errorsOnly(abi("QoreChainHybridHolderGuard.sol", "QoreChainHybridHolderGuard")),
].filter((e) => !seen.has(JSON.stringify(e)) && seen.add(JSON.stringify(e)));

const out = {
  note: "generated by scripts/sync-contracts.mjs from ../contracts; do not edit",
  chainId: 9800,
  nativeChainId: "qorechain-diana",
  deployment: { ...dep, issuer: bond.issuer, deployBlock: Number(dep.deployBlock) },
  fusd: "0x97143B771D34ddb9130b807b135Ae675A5a963CA",
  abi: {
    countersign: abi("Countersign.sol", "Countersign"),
    faucet: abi("DemoBondFaucet.sol", "DemoBondFaucet"),
    // the bond's and guard's errors, so reverts bubbling up through Countersign decode by name
    extraErrors: errors,
  },
};
const target = DIR === "deployments" ? "contracts.json" : "contracts.local.json";
writeFileSync(resolve(import.meta.dirname, "../src/generated", target), JSON.stringify(out, null, 2) + "\n");
console.log(`synced ${dep.label} -> src/generated/${target}: Countersign ${dep.countersign}, deploy block ${out.deployment.deployBlock}`);
