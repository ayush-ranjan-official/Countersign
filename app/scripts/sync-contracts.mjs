// Copies the live deployment (addresses, deploy block, config) and the ABIs from ../contracts into
// src/generated/contracts.json, so the app never hard-codes an address. Run after every deploy:
//   pnpm sync-contracts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const C = resolve(import.meta.dirname, "../../contracts");
const read = (p) => JSON.parse(readFileSync(resolve(C, p), "utf8"));
const abi = (file, name) => read(`out/${file}/${name}.json`).abi;

const dep = read("deployments/countersign-9800.json");
const bond = read("deployments/bond-9800.json");
const run = read("broadcast/DeployCountersign.s.sol/9800/run-latest.json");
const csReceipt = run.receipts.find((r) => r.contractAddress?.toLowerCase() === dep.countersign.toLowerCase());
if (!csReceipt) throw new Error("Countersign deploy receipt not found in the broadcast log");

const errorsOnly = (a) => a.filter((x) => x.type === "error");
const seen = new Set();
const errors = [
  ...errorsOnly(abi("CMTATStandalone.sol", "CMTATStandalone")),
  ...errorsOnly(abi("QoreChainHybridHolderRule.sol", "QoreChainHybridHolderRule")),
  ...errorsOnly(abi("QoreChainHybridHolderGuard.sol", "QoreChainHybridHolderGuard")),
].filter((e) => !seen.has(JSON.stringify(e)) && seen.add(JSON.stringify(e)));

const out = {
  note: "generated by scripts/sync-contracts.mjs from ../contracts; do not edit",
  chainId: 9800,
  nativeChainId: "qorechain-diana",
  deployment: { ...dep, issuer: bond.issuer, deployBlock: Number(BigInt(csReceipt.blockNumber)) },
  fusd: "0x97143B771D34ddb9130b807b135Ae675A5a963CA",
  abi: {
    countersign: abi("Countersign.sol", "Countersign"),
    faucet: abi("DemoBondFaucet.sol", "DemoBondFaucet"),
    // the bond's and guard's errors, so reverts bubbling up through Countersign decode by name
    extraErrors: errors,
  },
};
writeFileSync(resolve(import.meta.dirname, "../src/generated/contracts.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`synced ${dep.label}: Countersign ${dep.countersign}, deploy block ${out.deployment.deployBlock}`);
